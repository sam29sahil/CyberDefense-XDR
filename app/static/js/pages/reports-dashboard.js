/* ==========================================================================
   reports-dashboard.js — page module for app/reports-dashboard.html
   Depends on: REPORTS_DATA, SCHEDULED_REPORTS_DATA (data/reports-data.js),
   XDR_CHART_DEFAULTS, XDR_PALETTE, XDRTable, XDRUtils
   ========================================================================== */

   (function () {
    const reports = REPORTS_DATA;
    const scheduled = SCHEDULED_REPORTS_DATA;
    const now = new Date("2026-07-24T09:58:00Z");
  
    const thisMonth = reports.filter((r) => r.generatedAt.startsWith(now.toISOString().slice(0, 7)));
    const avgSizeMb = reports.length ? Math.round(reports.reduce((s, r) => s + r.sizeKb, 0) / reports.length / 1024 * 10) / 10 : 0;
  
    document.getElementById("reportsSummary").textContent = `${reports.length} reports generated · ${scheduled.filter((s) => s.status === "active").length} active schedules`;
  
    const kpis = [
      { label: "Total Reports", value: reports.length, accent: "accent-primary", icon: "bi-file-earmark-text" },
      { label: "Generated This Month", value: thisMonth.length, accent: "accent-success", icon: "bi-calendar-check" },
      { label: "Active Schedules", value: scheduled.filter((s) => s.status === "active").length, accent: "accent-info", icon: "bi-calendar2-week" },
      { label: "Avg Report Size", value: `${avgSizeMb} MB`, accent: "accent-warning", icon: "bi-hdd" },
    ];
    document.getElementById("kpiRow").innerHTML = kpis.map((k) => `
      <div class="col-lg-3 col-md-6 col-6">
        <div class="card stat-card ${k.accent} h-100">
          <div class="eyebrow"><i class="bi ${k.icon}"></i> ${k.label}</div>
          <div class="stat-value">${k.value}</div>
        </div>
      </div>`).join("");
  
    // ---------- Reports by type ----------
    const types = [...new Set(reports.map((r) => r.type))];
    const typeCounts = types.map((t) => reports.filter((r) => r.type === t).length);
    new Chart(document.getElementById("typeBreakdownChart"), {
      type: "bar",
      data: { labels: types, datasets: [{ data: typeCounts, backgroundColor: XDR_PALETTE.activity[0], borderRadius: 3 }] },
      options: { ...XDR_CHART_DEFAULTS, indexAxis: "y", plugins: { legend: { display: false } } },
    });
  
    // ---------- Recent reports table ----------
    const columns = [
      { key: "name", label: "Report", sortable: true,
        render: (r) => `<div class="d-flex align-items-center gap-2"><span class="report-icon-tile"><i class="bi bi-file-earmark-text"></i></span>
          <div><div style="font-weight:600;">${XDRUtils.escapeHtml(r.name)}</div><div class="text-xs text-muted">${r.id} · ${r.pages} pages</div></div></div>` },
      { key: "type", label: "Type", sortable: true, render: (r) => `<span class="badge badge-neutral">${r.type}</span>` },
      { key: "format", label: "Format", sortable: true, render: (r) => `<span class="format-chip">${r.format}</span>` },
      { key: "generatedBy", label: "Generated By", sortable: true },
      { key: "generatedAt", label: "Generated", sortable: true, render: (r) => XDRUtils.formatTime(r.generatedAt) },
      { key: "status", label: "Status", sortable: true,
        render: (r) => `<span class="badge ${r.status === "ready" ? "badge-success" : r.status === "generating" ? "badge-warning" : "badge-danger"}">${r.status}</span>` },
      { key: "actions", label: "", sortable: false,
        render: (r) => `<div class="row-actions"><a href="pdf-preview.html?id=${r.id}" class="btn btn-icon btn-ghost btn-sm" title="Preview"><i class="bi bi-eye"></i></a>
          <button class="btn btn-icon btn-ghost btn-sm" title="Download"><i class="bi bi-download"></i></button></div>` },
    ];
  
    new XDRTable({
      tableEl: document.getElementById("reportsTable"),
      searchInput: document.getElementById("reportSearch"),
      paginationEl: document.getElementById("reportsPagination"),
      data: reports,
      pageSize: 8,
      searchKeys: ["name", "type", "generatedBy"],
      columns,
    });
  })();
  